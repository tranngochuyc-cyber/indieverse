const fs=require('node:fs');
const path=require('node:path');
const root=__dirname;
const output=path.join(root,'dist');
// A custom domain serves this artifact at /; a project Pages URL uses /indieverse.
const base=(process.env.INDIEVERSE_PAGES_BASE||'').replace(/\/$/,'');
if(base&&!/^\/[a-z0-9_-]+$/i.test(base))throw Error('INDIEVERSE_PAGES_BASE must be a single URL path segment.');
const domain=process.env.INDIEVERSE_PAGES_DOMAIN||'indieverse.id.vn';
if(!/^[a-z0-9.-]+\.[a-z]{2,}$/i.test(domain))throw Error('Invalid Indieverse Pages domain.');
fs.mkdirSync(output,{recursive:true});
fs.cpSync(path.join(root,'assets'),path.join(output,'assets'),{recursive:true});
for(const name of ['style.css','pages.css','interiors.css','app.js','interiors.js','indie-hub.js','motion.js','pages-api.js','pages-overrides.js','favicon.svg',"discovery-engine.js","community-config.js","community.js","review-perspectives.js","experience-v8.js","experience-v8.css"])fs.copyFileSync(path.join(root,name),path.join(output,name));
let html=fs.readFileSync(path.join(root,'index.html'),'utf8');
html=html.replace('<script src="/app.js"></script>','<script>window.INDIEVERSE_PAGES=true</script><script src="/pages-api.js"></script><script src="/app.js"></script>');
html=html.replace('<script src="/motion.js"></script>','<script src="/pages-overrides.js"></script><script src="/motion.js"></script>');
html=html.replace('window.INDIEVERSE_PAGES=true',`window.INDIEVERSE_PAGES=true;window.INDIEVERSE_BASE=${JSON.stringify(base)}`);
const prefix=base?base+'/':'/';
html=html.replaceAll('href="/',`href="${prefix}`).replaceAll('src="/',`src="${prefix}`);
fs.writeFileSync(path.join(output,'index.html'),html);
fs.writeFileSync(path.join(output,'404.html'),html);
fs.writeFileSync(path.join(output,'.nojekyll'),'');
fs.writeFileSync(path.join(output,'CNAME'),domain+'\n');
fs.writeFileSync(path.join(output,'catalog.json'),JSON.stringify(require('./data/catalog.cjs')));
console.log('Built GitHub Pages site in dist/');
